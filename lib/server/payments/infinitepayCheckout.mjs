/**
 * EMPROVEX — InfinitePay checkout adapter (server-only, NOT wired to production).
 *
 * Documentation: https://ajuda.infinitepay.io/pt-BR/articles/10766888-como-usar-o-checkout-integrado-da-infinitepay
 *
 * Checkout is an individual payment, NOT an automatically renewing subscription.
 * This module does not update billingAccounts, billingCycles or access controls.
 */
import { createHash, createHmac } from 'node:crypto';

const API_BASE = 'https://api.checkout.infinitepay.io';
const EVENTS = new Set(['created', 'paid', 'settled', 'canceled', 'refunded', 'payment_failed']);

function requiredString(value, label) {
  if (typeof value !== 'string' || !value.trim()) {
    throw new Error(label + ' is required.');
  }
  return value.trim();
}

function validHttpsUrl(value, label) {
  const raw = requiredString(value, label);
  let url;
  try {
    url = new URL(raw);
  } catch {
    throw new Error(label + ' must be a valid HTTPS URL.');
  }
  if (url.protocol !== 'https:' || !url.hostname || url.username || url.password) {
    throw new Error(label + ' must be a valid HTTPS URL without embedded credentials.');
  }
  return url.toString();
}

function assertMonth(referenceMonth) {
  const month = requiredString(referenceMonth, 'referenceMonth');
  if (!/^20[0-9]{2}-(0[1-9]|1[0-2])$/.test(month)) {
    throw new Error('referenceMonth must have YYYY-MM format.');
  }
  return month;
}

function assertAmount(amountCents) {
  if (!Number.isSafeInteger(amountCents) || amountCents <= 0) {
    throw new Error('amountCents must be a positive integer of cents.');
  }
  return amountCents;
}

/**
 * Stable, opaque external order identifier for one workspace billing cycle.
 * Secret must be server-side and stable across redeploys.
 * Never publish workspaceId, UG, authorizedEmail or customer details to checkout.
 */
export function makeOrderNsu({ workspaceId, referenceMonth, orderIdSecret }) {
  const workspace = requiredString(workspaceId, 'workspaceId');
  const month = assertMonth(referenceMonth);
  const secret = requiredString(orderIdSecret, 'orderIdSecret');
  if (secret.length < 32) throw new Error('orderIdSecret must be at least 32 characters.');
  const opaqueId = createHmac('sha256', secret)
    .update('infinitepay\u0000' + workspace + '\u0000' + month)
    .digest('hex')
    .slice(0, 24);
  return 'epx-' + month.replace('-', '') + '-' + opaqueId;
}

/**
 * Offline construction of a truthful SaaS payment request.
 * A separate genuine educational product must have its own product contract.
 */
export function buildCheckoutRequest({
  orderNsu, referenceMonth, amountCents, redirectUrl, webhookUrl, validUntil,
}) {
  const order = requiredString(orderNsu, 'orderNsu');
  if (!/^epx-[0-9]{6}-[a-f0-9]{24}$/.test(order)) {
    throw new Error('orderNsu must be generated by makeOrderNsu.');
  }
  const month = assertMonth(referenceMonth);
  if (order.slice(4, 10) !== month.replace('-', '')) {
    throw new Error('orderNsu and referenceMonth mismatch.');
  }
  const amount = assertAmount(amountCents);
  const redirect = validHttpsUrl(redirectUrl, 'redirectUrl');
  const webhook = validHttpsUrl(webhookUrl, 'webhookUrl');
  const expiry = requiredString(validUntil, 'validUntil');
  const epoch = Date.parse(expiry);
  if (!Number.isFinite(epoch) || !/(Z|[+-][0-9]{2}:[0-9]{2})$/.test(expiry)) {
    throw new Error('validUntil must be an ISO-8601 date with timezone.');
  }
  return Object.freeze({
    order_nsu: order,
    redirect_url: redirect,
    items: [{ quantity: 1, price: amount, description: 'EMPROVEX - Plano Completo - ' + month }],
    options: {
      single_payment: true,
      valid_until: expiry,
      require_delivery_address: false,
      payment_methods_enabled: ['pix', 'credit_card'],
    },
    webhook: {
      url: webhook,
      events: ['paid', 'settled', 'refunded', 'canceled', 'payment_failed'],
    },
  });
}

/**
 * Classify notifications as signals only: NEVER use webhook body alone to mark paid.
 * An authenticated payment_check plus durable transactional reconciliation is required.
 */
export function classifyPaymentNotification(payload) {
  if (!payload || typeof payload !== 'object' || Array.isArray(payload)) {
    return { accepted: false, reason: 'INVALID_PAYLOAD' };
  }
  const eventName = payload.event || payload.type;
  const orderNsu = payload.order_nsu;
  if (typeof eventName !== 'string' || !EVENTS.has(eventName)) {
    return { accepted: false, reason: 'UNKNOWN_EVENT' };
  }
  if (typeof orderNsu !== 'string' || !/^epx-[0-9]{6}-[a-f0-9]{24}$/.test(orderNsu)) {
    return { accepted: false, reason: 'UNKNOWN_ORDER' };
  }
  if (typeof payload.transaction_nsu !== 'string' || !payload.transaction_nsu.trim()) {
    return { accepted: false, reason: 'MISSING_TRANSACTION' };
  }
  return {
    accepted: true,
    event: eventName,
    orderNsu,
    transactionNsu: payload.transaction_nsu.trim(),
    needsAuthenticatedReconciliation: true,
    mayAutoGrantAccess: false,
  };
}

export function eventFingerprint({ orderNsu, transactionNsu, event }) {
  const order = requiredString(orderNsu, 'orderNsu');
  const tx = requiredString(transactionNsu, 'transactionNsu');
  const name = requiredString(event, 'event');
  return createHash('sha256').update(order + '\u0000' + tx + '\u0000' + name).digest('hex');
}

/**
 * Assess a result from payment_check called with the original stored order,
 * transaction and slug. This is a PURE decision; no Firestore writes here.
 */
export function assessPaymentCheck({ amountCents, paymentCheck }) {
  const amount = assertAmount(amountCents);
  if (!paymentCheck || typeof paymentCheck !== 'object' || paymentCheck.paid !== true) {
    return { verified: false, reason: 'NOT_PAID' };
  }
  if (paymentCheck.success !== true) {
    return { verified: false, reason: 'CHECK_FAILED' };
  }
  if (!Number.isSafeInteger(paymentCheck.amount) || paymentCheck.amount !== amount) {
    return { verified: false, reason: 'AMOUNT_MISMATCH' };
  }
  if (!Number.isSafeInteger(paymentCheck.paid_amount) || paymentCheck.paid_amount < amount) {
    return { verified: false, reason: 'UNDERPAID' };
  }
  if (!['pix', 'credit_card'].includes(paymentCheck.capture_method)) {
    return { verified: false, reason: 'METHOD_UNKNOWN' };
  }
  return { verified: true, reason: 'PAID_VERIFIED' };
}

/**
 * Explicit opt-in required to make ANY network call, in addition to API Key.
 * Does not provide a public route, schedule payments, or activate live billing.
 */
export async function callInfinitePay({ operation, apiKey, payload, allowExternalCall = false, fetchImpl = fetch }) {
  if (!allowExternalCall) throw new Error('External InfinitePay calls are disabled by default.');
  const key = requiredString(apiKey, 'apiKey');
  if (key.length < 16) throw new Error('Invalid API Key.');
  const endpoints = { links: '/links', payment_check: '/payment_check' };
  if (!Object.hasOwn(endpoints, operation)) throw new Error('Unsupported InfinitePay operation.');
  const response = await fetchImpl(API_BASE + endpoints[operation], {
    method: 'POST',
    headers: { 'X-Api-Key': key, 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
    cache: 'no-store',
  });
  if (!response || !response.ok) {
    // Do not leak third-party response bodies: they can echo secrets/PII.
    throw new Error('InfinitePay upstream request failed.');
  }
  return response.json();
}
